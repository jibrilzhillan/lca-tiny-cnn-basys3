# run_regression.py
# One command: generate vectors, simulate the real cnn_core on N images, summarise FPGA vs Python.
"""Many-image regression of the real CNN core against the Python integer model (test R1).

Steps:
  1. gen_regression_vectors.py: N TuSimple test images + expected logits/class
  2. prepare_quant_params.py:   build-local cnn_quant_params.vh from mem/quant_params.txt
  3. copy the weight .mem files from mem/ into the run directory
  4. compile and run hw/tb/system/tb_cnn_regression.v with Icarus Verilog or Vivado XSim
  5. write summary.md (agreement, accuracy, confusion matrices, latency) next to reg_results.csv

Examples (from the repo root):
  python hw/tools/run_regression.py                       # 128 images, XSim if Vivado is found, else Icarus
  python hw/tools/run_regression.py --count 256 --sim icarus
  python hw/tools/run_regression.py --sim xsim --vivado-bin "D:/AMD/2026.1/Vivado/bin"
  python hw/tools/run_regression.py --report report/regression   # also copy results for the report

About 1.4 s per image with Icarus (128 images: ~3 min; the full test set of 2,216: ~50 min).
"""
import argparse
import csv
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
HW = ROOT / 'hw'
MEM = ROOT / 'mem'
NAMES = ('LEFT', 'STRAIGHT', 'RIGHT')
RTL = [
    'rtl/lib/rom.v', 'rtl/lib/ram.v', 'rtl/cnn/cnn_ctrl.v', 'rtl/cnn/cnn_core.v',
    'rtl/cnn/conv/mac.v', 'rtl/cnn/conv/relu_requant.v', 'rtl/cnn/conv/address_generator.v',
    'rtl/cnn/conv/conv_engine.v',
    'rtl/cnn/classifier/maxpool_engine.v', 'rtl/cnn/classifier/fc_engine.v', 'rtl/cnn/classifier/argmax3.v',
]
TB = 'tb/system/tb_cnn_regression.v'
WEIGHTS = ['conv_weight.mem', 'conv_bias.mem', 'fc_weight.mem', 'fc_bias.mem', 'test_images.mem']


def run(cmd, cwd, log=None):
    print('>', ' '.join(str(c) for c in cmd), flush=True)
    p = subprocess.run([str(c) for c in cmd], cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                       text=True, shell=(os.name == 'nt' and str(cmd[0]).endswith('.bat')))
    (Path(cwd) / f'{log or Path(str(cmd[0])).stem}.log').write_text(p.stdout)
    return p.returncode, p.stdout


def find_vivado(arg):
    if arg:
        return Path(arg)
    if os.environ.get('XILINX_VIVADO'):
        return Path(os.environ['XILINX_VIVADO']) / 'bin'
    xvlog = shutil.which('xvlog')
    return Path(xvlog).parent if xvlog else None


def simulate(sim, work, vivado_bin):
    n = len((work / 'reg_labels.mem').read_text().split())
    (work / 'reg_config.vh').write_text(f'`define REG_NUM_IMAGES {n}\n', encoding='ascii')
    incs = [HW / 'rtl/include', HW / 'tb/common', work]
    srcs = [HW / TB] + [HW / f for f in RTL]
    if sim == 'icarus':
        cmd = ['iverilog', '-g2005', '-DCNN_USE_QUANT_CONFIG', '-DREG_USE_CONFIG', '-o', 'reg_sim']
        cmd += [x for i in incs for x in ('-I', i)] + srcs
        rc, out = run(cmd, work)
        if rc:
            sys.exit('COMPILE FAILED:\n' + out)
        return run(['vvp', '-n', 'reg_sim'], work)[1]
    ext = '.bat' if os.name == 'nt' else ''
    tool = lambda n: vivado_bin / f'{n}{ext}'
    cmd = [tool('xvlog'), '-d', 'CNN_USE_QUANT_CONFIG', '-d', 'REG_USE_CONFIG'] + [x for i in incs for x in ('-i', i)] + srcs
    for step in (cmd, [tool('xelab'), 'tb_cnn_regression', '-s', 'reg_snap']):
        rc, out = run(step, work)
        if rc:
            sys.exit(f'{Path(str(step[0])).stem} FAILED:\n' + out)
    return run([tool('xsim'), 'reg_snap', '-R'], work)[1]


def summarise(work):
    manifest = {int(r['index']): r for r in csv.DictReader(open(work / 'reg_manifest.csv'))}
    rows = list(csv.DictReader(open(work / 'reg_results.csv')))
    n = len(rows)
    agree = sum(r['match'].strip() == '1' for r in rows)
    hw_ok = sum(r['hw_class'] == r['label'] for r in rows)
    py_ok = sum(r['py_class'] == r['label'] for r in rows)
    cycles = sorted({int(r['cycles']) for r in rows})
    agree_cm = [[0] * 3 for _ in range(3)]
    label_cm = [[0] * 3 for _ in range(3)]
    for r in rows:
        agree_cm[int(r['py_class'])][int(r['hw_class'])] += 1
        label_cm[int(r['label'])][int(r['hw_class'])] += 1
    counts = [sum(label_cm[i]) for i in range(3)]

    def table(cm, rows_name):
        s = f'| {rows_name} \\ FPGA | ' + ' | '.join(NAMES) + ' | Total |\n|---|---|---|---|---|\n'
        for i in range(3):
            s += f'| {NAMES[i]} | ' + ' | '.join(str(v) for v in cm[i]) + f' | {sum(cm[i])} |\n'
        return s

    per_class = ' · '.join(
        f'{NAMES[i]} {label_cm[i][i]}/{counts[i]}' + (f' ({label_cm[i][i] / counts[i]:.0%})' if counts[i] else '')
        for i in range(3))
    md = f"""# Regression R1: FPGA RTL vs Python model, {n} test images

Generated by `hw/tools/run_regression.py`. Images: random sample of the TuSimple **test** set
(`sw/tusimple_preprocessed_test.npz`, never used for training). Weights: `mem/` (D25).

| Measure | Result |
|---|---|
| Images simulated | {n} |
| **FPGA (RTL) vs Python integer model** | **{agree}/{n} identical** (3 logits and class, bit for bit) |
| Accuracy vs true label, FPGA | {hw_ok}/{n} = {hw_ok / n:.1%} |
| Accuracy vs true label, Python | {py_ok}/{n} = {py_ok / n:.1%} |
| Per class (FPGA) | {per_class} |
| Latency | {', '.join(f'{c:,}' for c in cycles)} cycles on every image ({cycles[0] / 1e5:.3f} ms at 100 MHz) |

## Agreement: Python class (rows) vs FPGA class (columns)

All values off the diagonal mean a hardware bug. They should all be 0.

{table(agree_cm, 'Python')}
## Accuracy: true label (rows) vs FPGA class (columns)

Values off the diagonal are model errors (the Python model makes the same ones).

{table(label_cm, 'Label')}
Per-image results: `reg_results_full.csv` (columns: index, dataset index, TuSimple path, label,
Python and FPGA class, Python and FPGA logits, cycles, match).
"""
    (work / 'summary.md').write_text(md, encoding='utf-8')
    with open(work / 'reg_results_full.csv', 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['index', 'dataset_index', 'path', 'label', 'py_class', 'hw_class', 'py_logit0', 'py_logit1',
                    'py_logit2', 'hw_logit0', 'hw_logit1', 'hw_logit2', 'cycles', 'status'])
        for r in rows:
            m = manifest[int(r['index'])]
            w.writerow([r['index'], m['dataset_index'], m['path'], NAMES[int(r['label'])], NAMES[int(r['py_class'])],
                        NAMES[int(r['hw_class'])], r['py_logit0'], r['py_logit1'], r['py_logit2'], r['hw_logit0'],
                        r['hw_logit1'], r['hw_logit2'], r['cycles'], 'MATCH' if r['match'].strip() == '1' else 'MISMATCH'])
    return agree == n


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--count', type=int, default=128)
    p.add_argument('--all', action='store_true', help='whole test set (2,216 images)')
    p.add_argument('--seed', type=int, default=2026)
    p.add_argument('--sim', choices=['auto', 'icarus', 'xsim'], default='auto')
    p.add_argument('--vivado-bin', help='Vivado bin folder (default: XILINX_VIVADO or PATH)')
    p.add_argument('--work', type=Path, default=HW / 'vivado/build/regression')
    p.add_argument('--report', type=Path, help='also copy summary.md and the CSVs here')
    a = p.parse_args()

    vivado = find_vivado(a.vivado_bin)
    sim = a.sim
    if sim == 'auto':
        sim = 'xsim' if vivado else 'icarus'
    if sim == 'xsim' and not vivado:
        sys.exit('Vivado not found: pass --vivado-bin or use --sim icarus')

    work = a.work.resolve()
    work.mkdir(parents=True, exist_ok=True)
    py = sys.executable
    gen = [py, '-I', HW / 'tools/gen_regression_vectors.py', '--out', work, '--seed', a.seed]
    gen += ['--all'] if a.all else ['--count', a.count]
    rc, out = run(gen, work, 'gen_regression_vectors')
    print(out.strip())
    if rc:
        sys.exit('vector generation failed')
    if run([py, '-I', HW / 'tools/prepare_quant_params.py', '--input', MEM / 'quant_params.txt',
            '--output', work / 'cnn_quant_params.vh'], work, 'prepare_quant_params')[0]:
        sys.exit('quant header failed, see prepare_quant_params.log')
    for f in WEIGHTS:
        shutil.copy(MEM / f, work / f)

    out = simulate(sim, work, vivado)
    for line in out.splitlines():
        if line.startswith(('REGRESSION', 'TEST ', 'ERROR', '  ')):
            print(line)
    if 'TEST PASSED' not in out and 'TEST FAILED' not in out:
        sys.exit('simulation did not finish, see the simulator log in ' + str(work))
    ok = summarise(work) and 'TEST PASSED' in out
    print('summary:', work / 'summary.md')
    if a.report:
        a.report.mkdir(parents=True, exist_ok=True)
        for f in ('summary.md', 'reg_results_full.csv'):
            shutil.copy(work / f, a.report / f)
        print('copied to', a.report)
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
